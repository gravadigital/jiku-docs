-- jiku-docs: initial schema (section 11 of the specification, adjusted by D-3 of the
-- integration decisions: attachments live in core's file service, so the attachment row keeps
-- `core_file_id` instead of a storage key of its own).
--
-- Timestamps are written by the service truncated to milliseconds: what is stored is exactly
-- what replies show, and what keyset cursors compare against.

CREATE EXTENSION IF NOT EXISTS unaccent;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_ts_config WHERE cfgname = 'es_unaccent') THEN
    CREATE TEXT SEARCH CONFIGURATION es_unaccent (COPY = spanish);
    ALTER TEXT SEARCH CONFIGURATION es_unaccent
      ALTER MAPPING FOR hword, hword_part, word WITH unaccent, spanish_stem;
  END IF;
END
$$;

-- ---------------------------------------------------------------- folders and ACL

CREATE TABLE folders (
  id               text PRIMARY KEY,                 -- ULID
  parent_id        text REFERENCES folders(id),
  name             text NOT NULL,
  path             text NOT NULL,                    -- materialised: '/clients/acme/pzt/'
  inherit_acl      boolean NOT NULL DEFAULT true,
  external_blocked boolean NOT NULL DEFAULT false,   -- effective = OR with the ancestors
  sharing_blocked  boolean NOT NULL DEFAULT false,   -- effective = OR with the ancestors
  created_by       text NOT NULL,
  created_at       timestamptz NOT NULL,
  updated_at       timestamptz NOT NULL,
  deleted_at       timestamptz
);
CREATE UNIQUE INDEX folders_path_uq ON folders (path) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX folders_name_uq ON folders (parent_id, lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX folders_parent ON folders (parent_id);

CREATE TABLE folder_rules (
  folder_id      text NOT NULL REFERENCES folders(id) ON DELETE CASCADE,
  principal_type text NOT NULL CHECK (principal_type IN ('role','user')),
  principal      text NOT NULL,
  permission     text NOT NULL CHECK (permission IN ('read','write','manage')),
  PRIMARY KEY (folder_id, principal_type, principal)
);

-- Version of the folder tree (folders + rules). Bumped in the same transaction as any change,
-- so the in-memory ACL cache knows when to reload.
CREATE TABLE tree_state (
  id      integer PRIMARY KEY CHECK (id = 1),
  version bigint NOT NULL
);
INSERT INTO tree_state (id, version) VALUES (1, 1);

