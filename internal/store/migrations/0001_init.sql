-- ---------------------------------------------------------------- documents

CREATE TABLE documents (
  id              text PRIMARY KEY,                  -- ULID generated by the client
  folder_id       text NOT NULL REFERENCES folders(id),
  file_name       text NOT NULL,
  path            text NOT NULL,                     -- folder path + file name, maintained on moves
  title           text NOT NULL,
  visibility      text NOT NULL DEFAULT 'internal' CHECK (visibility IN ('internal','public')),
  current_version integer NOT NULL,
  checksum        text NOT NULL,                     -- 'sha256:<hex>' of the current version
  size_bytes      integer NOT NULL,
  secret_warning  boolean NOT NULL DEFAULT false,    -- the secret detector flagged the current version
  created_by      text NOT NULL,
  created_at      timestamptz NOT NULL,
  updated_by      text NOT NULL,
  updated_at      timestamptz NOT NULL,
  deleted_at      timestamptz,
  deleted_by      text
);
CREATE UNIQUE INDEX documents_name_uq ON documents (folder_id, lower(file_name)) WHERE deleted_at IS NULL;
CREATE INDEX documents_folder ON documents (folder_id);
CREATE INDEX documents_path ON documents (path text_pattern_ops);
CREATE INDEX documents_updated ON documents (updated_at, id);
CREATE INDEX documents_deleted ON documents (deleted_at) WHERE deleted_at IS NOT NULL;

CREATE TABLE document_versions (
  document_id text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  version     integer NOT NULL,
  storage_key text NOT NULL,                         -- 'docs/<documentId>/<version>-<sha256>.md'
  checksum    text NOT NULL,
  size_bytes  integer NOT NULL,
  title       text NOT NULL,
  author      text NOT NULL,
  via         text NOT NULL CHECK (via IN ('human','agent','service')),
  session_id  text,
  message     text,
  created_at  timestamptz NOT NULL,
  PRIMARY KEY (document_id, version)
);
CREATE INDEX document_versions_storage ON document_versions (storage_key);

CREATE TABLE document_relations (
  document_id text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  entity_type text NOT NULL CHECK (entity_type IN ('client','project','requirement','task')),
  entity_id   bigint NOT NULL,
  project_id  bigint,                                -- resolved project, for filter.projectId
  PRIMARY KEY (document_id, entity_type, entity_id)
);
CREATE INDEX document_relations_entity ON document_relations (entity_type, entity_id);
CREATE INDEX document_relations_project ON document_relations (project_id);

CREATE TABLE document_topics (
  document_id text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  topic       text NOT NULL,
  PRIMARY KEY (document_id, topic)
);
CREATE INDEX document_topics_topic ON document_topics (topic);

CREATE TABLE document_locks (
  document_id text PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE,
  session_id  text NOT NULL,
  holder      text NOT NULL,
  via         text NOT NULL CHECK (via IN ('human','agent')),
  expires_at  timestamptz NOT NULL
);
CREATE INDEX document_locks_expiry ON document_locks (expires_at);

-- D-3: the bytes live in core's file service; this row maps the document attachment to it.
CREATE TABLE attachments (
  id           text PRIMARY KEY,
  document_id  text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  file_name    text NOT NULL,
  mime_type    text NOT NULL,
  size_bytes   bigint NOT NULL,
  checksum     text NOT NULL,                        -- 'sha256:<hex>' declared at request time
  core_file_id bigint NOT NULL,                      -- files.id in core
  status       text NOT NULL CHECK (status IN ('pending','ready','deleted')),
  uploaded_by  text NOT NULL,
  created_at   timestamptz NOT NULL,
  confirmed_at timestamptz,
  deleted_at   timestamptz
);
CREATE INDEX attachments_document ON attachments (document_id);
CREATE INDEX attachments_pending ON attachments (created_at) WHERE status = 'pending';

CREATE TABLE content_uploads (
  id           text PRIMARY KEY,
  checksum     text NOT NULL,
  size_bytes   integer NOT NULL,
  storage_key  text NOT NULL,                        -- 'uploads/<id>'
  requested_by text NOT NULL,
  created_at   timestamptz NOT NULL,
  expires_at   timestamptz NOT NULL,
  consumed_at  timestamptz
);

-- ---------------------------------------------------------------- outbox

CREATE TABLE changelog (
  seq          bigserial PRIMARY KEY,
  event_id     text NOT NULL UNIQUE,                 -- ULID
  type         text NOT NULL,
  entity_type  text NOT NULL,
  entity_id    text NOT NULL,
  folder_id    text,
  document_id  text,
  payload      jsonb NOT NULL,                       -- full event envelope (without seq)
  occurred_at  timestamptz NOT NULL,
  published_at timestamptz
);
CREATE INDEX changelog_unpublished ON changelog (seq) WHERE published_at IS NULL;
CREATE INDEX changelog_occurred ON changelog (occurred_at);

CREATE FUNCTION changelog_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_notify('jiku_docs_changelog', '');
  RETURN NULL;
END
$$;
CREATE TRIGGER changelog_notify AFTER INSERT ON changelog
  FOR EACH STATEMENT EXECUTE FUNCTION changelog_notify();

-- ---------------------------------------------------------------- shares

CREATE TABLE shares (
  id                  text PRIMARY KEY,              -- ULID generated by the client
  document_id         text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  token_hash          bytea NOT NULL UNIQUE,         -- sha256(token); never the token itself
  token_retry_cipher  bytea,                         -- token encrypted for retries; erased after 5 min
  request_hash        bytea NOT NULL,                -- fingerprint of the shares.new payload, for idempotency
  mode                text NOT NULL CHECK (mode IN ('latest','pinned')),
  version             integer,
  include_attachments boolean NOT NULL DEFAULT true,
  note                text,
  created_by          text NOT NULL,
  created_at          timestamptz NOT NULL,
  expires_at          timestamptz NOT NULL,
  revoked_at          timestamptz,
  revoked_by          text,
  revoke_reason       text CHECK (revoke_reason IN ('manual','document_deleted')),
  access_count        bigint NOT NULL DEFAULT 0,
  last_access_at      timestamptz,
  CHECK (mode = 'latest' OR version IS NOT NULL)
);
CREATE INDEX shares_document ON shares (document_id);

CREATE TABLE share_accesses (
  share_id      text NOT NULL REFERENCES shares(id) ON DELETE CASCADE,
  accessed_at   timestamptz NOT NULL,
  kind          text NOT NULL CHECK (kind IN ('document','attachment')),
  attachment_id text,
  ip_hash       bytea NOT NULL,                      -- HMAC of the IP with a service key
  user_agent    text                                 -- truncated to 200 characters
);
CREATE INDEX share_accesses_share ON share_accesses (share_id, accessed_at DESC);
CREATE INDEX share_accesses_time ON share_accesses (accessed_at);

-- ---------------------------------------------------------------- index

CREATE TABLE index_chunks (
  document_id  text NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  version      integer NOT NULL,
  chunk_no     integer NOT NULL,
  heading_path text[] NOT NULL,
  body         text NOT NULL,
  tsv          tsvector NOT NULL,                    -- title and headings weight A, body weight B
  PRIMARY KEY (document_id, chunk_no)
);
CREATE INDEX index_chunks_tsv ON index_chunks USING gin (tsv);

-- Which version of each document the index holds (a document can have zero chunks).
CREATE TABLE index_status (
  document_id text PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE,
  version     integer NOT NULL,
  indexed_at  timestamptz NOT NULL
);

-- ---------------------------------------------------------------- service state

-- Small key/value for operational state: last run of daily jobs, changelog purge watermark.
CREATE TABLE service_state (
  key        text PRIMARY KEY,
  value      jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
